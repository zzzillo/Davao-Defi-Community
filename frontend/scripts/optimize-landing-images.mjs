const imports = []
const exports = []
let totalBytes = 0

async function generate(name, source, widths, logo = false) {
  const input = fileURLToPath(new URL(source, sourceRoot))
  const metadata = await sharp(input).metadata()
  // Do not upscale small sources or generate duplicate full-size variants.
  const targetWidths = [...new Set(widths.map(width => Math.min(width, metadata.width)))]
  const variants = []

  for (const width of targetWidths) {
    const filename = `${name}-${width}.webp`
    const info = await sharp(input)
      .rotate()
      .resize({ width, ...(logo ? { height: 112, fit: 'inside' } : {}), withoutEnlargement: true })
      .webp({ quality: logo ? 85 : 80, effort: 5 })
      .toFile(fileURLToPath(new URL(filename, outputRoot)))
    const identifier = `${name}${width}`
    // Keep even tiny logos as cacheable files, not base64 inside JavaScript.
    imports.push(`import ${identifier} from '../assets/landing/${filename}?no-inline'`)
    variants.push({ identifier, ...info })
    totalBytes += info.size
  }

  const fallback = variants.find(variant => variant.width >= 768) ?? variants.at(-1)
  const srcSet = variants.map(variant => `\${${variant.identifier}} ${variant.width}w`).join(', ')
  exports.push(`export const ${name} = {\n  src: ${fallback.identifier},\n  srcSet: \`${srcSet}\`,\n  width: ${fallback.width},\n  height: ${fallback.height},\n}`)
}

for (const [name, source] of Object.entries(photos)) {
  await generate(name, source, [480, 768, 1152, 1536])
}
await generate('communityWide', 'team/community-wide.webp', [960, 1280, 1536])
await generate('communityPortrait', 'team/community-portrait.webp', [480, 768, 1351])
for (const [name, source] of Object.entries(logos)) {
  await generate(name, source, [352], true)
}

await writeFile(new URL('../src/data/landingImages.ts', import.meta.url),
  '// Generated by npm run optimize:landing. Edit the generator, not this file.\n'
  + imports.join('\n') + '\n\n' + exports.join('\n\n') + '\n')
console.log(`Generated ${imports.length} WebP assets (${Math.round(totalBytes / 1024)} KiB across all sizes).`)
